/**
 * Operating modes and density policies for Quick Dimension (QDIM),
 * matching Sections 8, 9, and 10 of the consolidated product specification.
 */
enum class QDimOperatingMode(val commandToken: String, val label: String) {
    QDIM_ALL("QDIM ALL", "Analyze Complete Drawing"),
    QDIM_SELECT("QDIM SELECT", "Analyze Selected Geometry"),
    QDIM_REGION("QDIM REGION", "Analyze Window Region")
}

enum class QDimDensityPolicy(val label: String, val description: String) {
    SPARSE("Sparse", "Essential overall bounding dimensions and primary hole diameter only."),
    BALANCED("Balanced (Default)", "Overall dimensions, hole pattern diameters, hole pitches, edge offsets, and fillet radii."),
    DETAILED("Detailed", "Comprehensive manufacturing dimensions including local shoulders, all radii, and inclined segments.")
}

data class DimensionStyleConfig(
    val standard: DraftingStandard = DraftingStandard.ISO,
    val baseTextHeightMm: Double = 3.5,
    val baseArrowLengthMm: Double = 3.0,
    val baseArrowWidthMm: Double = 1.0,
    val extensionLineGapMm: Double = 1.2,
    val extensionLineOvershootMm: Double = 1.8,
    val baselineTrackSpacingMm: Double = 9.0
)

/**
 * 10.1 AutoDimensionEngine
 * Responsibilities:
 * - Analyse selected or all sheet entities.
 * - Detect geometric relationships (overall width/height, hole patterns, concentric bores, center distances, edge offsets, fillet/arc radii, angles).
 * - Generate candidate dimensions following a 4-tier hierarchy and ISO 129-1 / ASME Y14.5 conventions.
 * - Avoid redundant pairwise hole-to-hole dimensions.
 * - Apply the selected dimension-density policy (Sparse, Balanced, Detailed).
 * - Preserve existing manual annotations without overwriting or duplicating them.
 */
object AutoDimensionEngine {

    fun removeAutoDimensions(allEntities: List<CadEntity>): List<CadEntity> {
        return allEntities.filterNot {
            (it is CadEntity.DimensionEntity && it.isAutoGenerated) ||
                (it is CadEntity.CenterMarkEntity && it.sourceEntityId != null)
        }
    }

    fun generateQuickDimensions(
        allEntities: List<CadEntity>,
        targetEntities: List<CadEntity>,
        density: QDimDensityPolicy = QDimDensityPolicy.BALANCED,
        replaceExistingAutoDims: Boolean = true,
        arrangementPreference: DimensionArrangementPreference = DimensionArrangementPreference.AUTO_CHAIN
    ): List<CadEntity> {
        return generateQuickDimensionsWithAlignmentReport(
            allEntities = allEntities,
            targetEntities = targetEntities,
            density = density,
            replaceExistingAutoDims = replaceExistingAutoDims,
            arrangementPreference = arrangementPreference
        ).first
    }

    fun generateQuickDimensionsWithAlignmentReport(
        allEntities: List<CadEntity>,
        targetEntities: List<CadEntity>,
        density: QDimDensityPolicy = QDimDensityPolicy.BALANCED,
        replaceExistingAutoDims: Boolean = true,
        arrangementPreference: DimensionArrangementPreference = DimensionArrangementPreference.AUTO_CHAIN,
        style: DimensionStyleConfig = DimensionStyleConfig(),
        precision: PrecisionFormatConfig = PrecisionFormatConfig(),
        storageUnit: CadUnit = CadUnit.MM,
        displayUnit: CadUnit = CadUnit.MM,
        viewport: ViewportTransform = ViewportTransform(pixelsPerModelUnit = 3.0f)
    ): Pair<List<CadEntity>, DimensionAlignmentReport> {
        val geometricTargets = targetEntities.filter {
            it !is CadEntity.DimensionEntity &&
                it !is CadEntity.CenterMarkEntity &&
                it !is CadEntity.XLineEntity &&
                it !is CadEntity.RayEntity &&
                it !is CadEntity.HatchEntity
        }
        if (geometricTargets.isEmpty()) {
            val emptyReport = DimensionAlignmentReport(
                placements = emptyList(),
                completenessFindings = emptyList(),
                unresolvedWarnings = emptyList(),
                layoutScore = 100.0,
                arrangementPreference = arrangementPreference,
                densityPolicy = density
            )
            return allEntities to emptyReport
        }

        val preservedEntities = if (replaceExistingAutoDims) {
            removeAutoDimensions(allEntities)
        } else {
            allEntities
        }

        val manualDimensions = preservedEntities.filterIsInstance<CadEntity.DimensionEntity>()
            .filter { !it.isAutoGenerated }

        val overallBounds = geometricTargets
            .map { it.boundingBox() }
            .reduce { acc, b -> acc.union(b) }

        val candidateDims = mutableListOf<CadEntity.DimensionEntity>()
        val centerMarks = mutableListOf<CadEntity.CenterMarkEntity>()

        // --- TIER 1: Primary Overall Bounding Width & Height ---
        val primaryPolyOrLineId = geometricTargets.firstOrNull {
            it is CadEntity.PolylineEntity || it is CadEntity.LineEntity
        }?.id

        if (overallBounds.width > 1e-3 && !hasEquivalentManualLinear(manualDimensions, DimensionType.LINEAR_HORIZONTAL, overallBounds.width)) {
            candidateDims.add(
                CadEntity.DimensionEntity(
                    dimensionType = DimensionType.LINEAR_HORIZONTAL,
                    anchor1 = Point2D(overallBounds.minX, overallBounds.maxY),
                    anchor2 = Point2D(overallBounds.maxX, overallBounds.maxY),
                    dimensionLinePoint = Point2D(overallBounds.center.x, overallBounds.maxY + 18.0),
                    sourceEntityIds = listOfNotNull(primaryPolyOrLineId),
                    isAutoGenerated = true,
                    hierarchyTier = DimensionHierarchyTier.PRIMARY_OVERALL
                )
            )
        }

        if (overallBounds.height > 1e-3 && !hasEquivalentManualLinear(manualDimensions, DimensionType.LINEAR_VERTICAL, overallBounds.height)) {
            candidateDims.add(
                CadEntity.DimensionEntity(
                    dimensionType = DimensionType.LINEAR_VERTICAL,
                    anchor1 = Point2D(overallBounds.minX, overallBounds.minY),
                    anchor2 = Point2D(overallBounds.minX, overallBounds.maxY),
                    dimensionLinePoint = Point2D(overallBounds.minX - 18.0, overallBounds.center.y),
                    sourceEntityIds = listOfNotNull(primaryPolyOrLineId),
                    isAutoGenerated = true,
                    hierarchyTier = DimensionHierarchyTier.PRIMARY_OVERALL
                )
            )
        }

        // --- Analyze Both Standalone Arcs AND Polyline Bulge Arcs (Fillets / Rounded Corners) ---
        data class DetectedArcFeature(
            val sourceEntityId: String,
            val arc: CadEntity.ArcEntity
        )

        val detectedArcs = mutableListOf<DetectedArcFeature>()
        val allLines = mutableListOf<Pair<String, CadEntity.LineEntity>>()
        geometricTargets.forEach { ent ->
            when (ent) {
                is CadEntity.ArcEntity -> detectedArcs.add(DetectedArcFeature(ent.id, ent))
                is CadEntity.LineEntity -> allLines.add(ent.id to ent)
                is CadEntity.PolylineEntity -> {
                    val prims = CadGeometryKernel.explodePolylineToPrimitives(ent)
                    prims.forEach { prim ->
                        when (prim) {
                            is CadEntity.ArcEntity -> detectedArcs.add(DetectedArcFeature(ent.id, prim))
                            is CadEntity.LineEntity -> allLines.add(ent.id to prim)
                            else -> Unit
                        }
                    }
                }
                else -> Unit
            }
        }

        // --- Analyze Circles / Holes & Repeated Patterns (ISO/ASME Radial Leader Fan-Out) ---
        val circles = geometricTargets.filterIsInstance<CadEntity.CircleEntity>()
            .sortedWith(compareBy<CadEntity.CircleEntity> { it.center.y }.thenBy { it.center.x })

        // Add automatic Center Marks for all holes/circles
        circles.forEach { circle ->
            centerMarks.add(
                CadEntity.CenterMarkEntity(
                    center = circle.center,
                    radius = circle.radius,
                    sourceEntityId = circle.id
                )
            )
        }

        // Run Section 10.4 Completeness & Symmetry Analysis
        val completenessFindings = DimensionAlignmentEngine.analyzeCompletenessAndRelationships(
            overallBounds = overallBounds,
            circles = circles,
            arcs = detectedArcs.map { it.arc }
        )

        val spanScale = max(overallBounds.width, overallBounds.height).coerceAtLeast(20.0)
        val innerTrackOffset = (spanScale * 0.085).coerceIn(8.0, 20.0)
        val outerTrackOffset = innerTrackOffset + (spanScale * 0.075).coerceIn(7.5, 16.0)
        val placedLeaderBoxes = mutableListOf<BoundingBox2D>()

        // Reserve linear dimension label boxes so radial/diametric leaders never collide with them
        val topTrackY = overallBounds.maxY + outerTrackOffset
        val bottomTrackY = overallBounds.minY - innerTrackOffset
        val leftTrackX = overallBounds.minX - outerTrackOffset
        val rightTrackX = overallBounds.maxX + innerTrackOffset
        placedLeaderBoxes.add(
            BoundingBox2D(
                overallBounds.center.x - spanScale * 0.16,
                topTrackY - 4.0,
                overallBounds.center.x + spanScale * 0.16,
                topTrackY + 6.0
            )
        )
        placedLeaderBoxes.add(
            BoundingBox2D(
                leftTrackX - 6.0,
                overallBounds.center.y - spanScale * 0.16,
                leftTrackX + 4.0,
                overallBounds.center.y + spanScale * 0.16
            )
        )

        // Group circles by layer + strict equal diameter (within 1e-4 tolerance) to generate verified pattern callouts like `6× ⌀10.00`
        val diameterGroups = circles.groupBy { it.layerName to (it.diameter * 10000.0).roundToLong() }
            .entries
            .sortedByDescending { it.key.second } // Largest diameter first

        diameterGroups.forEachIndexed { groupIdx, (_, group) ->
            // Prefer top-right or outer circle for cleanest unobstructed leader exit
            val representative = group.maxByOrNull { it.center.x * 0.75 + it.center.y } ?: group.first()
            val countPrefix = if (group.size > 1) "${group.size}× " else ""

            val maxConcentricRadius = circles
                .filter { it.center.distanceTo(representative.center) < 1.0 }
                .maxOfOrNull { it.radius } ?: representative.radius

            val placement = findBestLeaderPlacement(
                featureId = representative.id,
                center = representative.center,
                radius = representative.radius,
                minClearanceRadius = maxConcentricRadius,
                preferredBaseAngle = if (group.size > 1) {
                    overallBounds.center.angleToDeg(representative.center)
                } else {
                    22.0 + groupIdx * 25.0
                },
                allCircles = circles,
                allArcs = detectedArcs.map { it.arc },
                overallBounds = overallBounds,
                placedLeaderBoxes = placedLeaderBoxes,
                lockContactAngle = null
            )

            placedLeaderBoxes.add(placement.reservedBox)

            candidateDims.add(
                CadEntity.DimensionEntity(
                    dimensionType = DimensionType.DIAMETER,
                    anchor1 = representative.center,
                    anchor2 = placement.rimContactPoint,
                    dimensionLinePoint = placement.shoulderPoint,
                    customPrefix = countPrefix,
                    sourceEntityIds = group.map { it.id },
                    isAutoGenerated = true,
                    hierarchyTier = DimensionHierarchyTier.GEOMETRIC_CALLOUT
                )
            )
        }

        // --- Analyze Donuts (Inner & Outer Diameters) (Section 57) ---
        val donuts = geometricTargets.filterIsInstance<CadEntity.DonutEntity>()
        donuts.forEach { donut ->
            centerMarks.add(
                CadEntity.CenterMarkEntity(
                    center = donut.center,
                    radius = donut.outerRadius,
                    sourceEntityId = donut.id
                )
            )
        }
        val donutGroups = donuts.groupBy {
            Triple(
                it.layerName,
                (it.innerDiameter * 10000.0).roundToLong(),
                (it.outerDiameter * 10000.0).roundToLong()
            )
        }
        donutGroups.entries.forEachIndexed { dIdx, (_, dGroup) ->
            val repDonut = dGroup.maxByOrNull { it.center.x * 0.75 + it.center.y } ?: dGroup.first()
            val countPrefix = if (dGroup.size > 1) "${dGroup.size}× " else ""
            val outerPlacement = findBestLeaderPlacement(
                featureId = repDonut.id,
                center = repDonut.center,
                radius = repDonut.outerRadius,
                minClearanceRadius = repDonut.outerRadius,
                preferredBaseAngle = 38.0 + dIdx * 28.0,
                allCircles = circles,
                allArcs = detectedArcs.map { it.arc },
                overallBounds = overallBounds,
                placedLeaderBoxes = placedLeaderBoxes,
                lockContactAngle = null
            )
            placedLeaderBoxes.add(outerPlacement.reservedBox)
            candidateDims.add(
                CadEntity.DimensionEntity(
                    dimensionType = DimensionType.DIAMETER,
                    anchor1 = repDonut.center,
                    anchor2 = outerPlacement.rimContactPoint,
                    dimensionLinePoint = outerPlacement.shoulderPoint,
                    customPrefix = countPrefix,
                    sourceEntityIds = dGroup.map { it.id },
                    isAutoGenerated = true,
                    hierarchyTier = DimensionHierarchyTier.GEOMETRIC_CALLOUT
                )
            )
            if (repDonut.innerRadius > 1e-3) {
                val innerPlacement = findBestLeaderPlacement(
                    featureId = repDonut.id,
                    center = repDonut.center,
                    radius = repDonut.innerRadius,
                    minClearanceRadius = repDonut.outerRadius,
                    preferredBaseAngle = 142.0 - dIdx * 28.0,
                    allCircles = circles,
                    allArcs = detectedArcs.map { it.arc },
                    overallBounds = overallBounds,
                    placedLeaderBoxes = placedLeaderBoxes,
                    lockContactAngle = null
                )
                placedLeaderBoxes.add(innerPlacement.reservedBox)
                candidateDims.add(
                    CadEntity.DimensionEntity(
                        dimensionType = DimensionType.DIAMETER,
                        anchor1 = repDonut.center,
                        anchor2 = innerPlacement.rimContactPoint,
                        dimensionLinePoint = innerPlacement.shoulderPoint,
                        customPrefix = countPrefix,
                        sourceEntityIds = dGroup.map { it.id },
                        isAutoGenerated = true,
                        hierarchyTier = DimensionHierarchyTier.GEOMETRIC_CALLOUT
                    )
                )
            }
        }

        // --- Analyze Ellipses (Major & Minor Axis Aligned Dimensions) (Section 57) ---
        val ellipses = geometricTargets.filterIsInstance<CadEntity.EllipseEntity>()
        ellipses.forEach { ellipse ->
            centerMarks.add(
                CadEntity.CenterMarkEntity(
                    center = ellipse.center,
                    radius = min(ellipse.majorRadius, ellipse.minorRadius) * 0.5,
                    sourceEntityId = ellipse.id
                )
            )
            val rotDeg = ellipse.rotationAngleDeg
            val majP1 = ellipse.center.polarOffset(-ellipse.majorRadius, rotDeg)
            val majP2 = ellipse.center.polarOffset(ellipse.majorRadius, rotDeg)
            val majLinePt = ellipse.center.polarOffset(ellipse.minorRadius + innerTrackOffset, rotDeg + 90.0)
            candidateDims.add(
                CadEntity.DimensionEntity(
                    dimensionType = DimensionType.ALIGNED,
                    anchor1 = majP1,
                    anchor2 = majP2,
                    dimensionLinePoint = majLinePt,
                    sourceEntityIds = listOf(ellipse.id),
                    isAutoGenerated = true,
                    hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                )
            )
            if (density != QDimDensityPolicy.SPARSE && ellipse.minorRadius > 1e-3) {
                val minP1 = ellipse.center.polarOffset(-ellipse.minorRadius, rotDeg + 90.0)
                val minP2 = ellipse.center.polarOffset(ellipse.minorRadius, rotDeg + 90.0)
                val minLinePt = ellipse.center.polarOffset(ellipse.majorRadius + innerTrackOffset, rotDeg)
                candidateDims.add(
                    CadEntity.DimensionEntity(
                        dimensionType = DimensionType.ALIGNED,
                        anchor1 = minP1,
                        anchor2 = minP2,
                        dimensionLinePoint = minLinePt,
                        sourceEntityIds = listOf(ellipse.id),
                        isAutoGenerated = true,
                        hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                    )
                )
            }
        }

        if (density != QDimDensityPolicy.SPARSE) {
            // --- TIER 2: Secondary Dimensions (Edge-to-Hole Offsets, Hole Pitch Chains / Baselines / Ordinates) ---
            if (circles.isNotEmpty()) {
                val clusterTol = max(0.25, spanScale * 0.005)
                val rowsByY = clusterCirclesByCoord(circles, clusterTol) { it.center.y }
                val bottomRow = rowsByY.minByOrNull { row -> row.minOf { it.center.y } }.orEmpty().sortedBy { it.center.x }
                val colsByX = clusterCirclesByCoord(circles, clusterTol) { it.center.x }
                val rightCol = colsByX.maxByOrNull { col -> col.maxOf { it.center.x } }.orEmpty().sortedBy { it.center.y }

                if (arrangementPreference == DimensionArrangementPreference.ORDINATE) {
                    // Ordinate mode: emit X ordinate dimensions for distinct X hole columns and Y ordinate dimensions for distinct Y hole rows
                    val distinctXCols = colsByX.mapNotNull { col -> col.minByOrNull { it.center.y } }.sortedBy { it.center.x }
                    distinctXCols.forEach { hole ->
                        candidateDims.add(
                            CadEntity.DimensionEntity(
                                dimensionType = DimensionType.ORDINATE_X,
                                anchor1 = Point2D(hole.center.x, overallBounds.minY),
                                anchor2 = Point2D(hole.center.x, overallBounds.minY - innerTrackOffset),
                                dimensionLinePoint = Point2D(hole.center.x, overallBounds.minY - innerTrackOffset),
                                sourceEntityIds = listOf(hole.id),
                                isAutoGenerated = true,
                                hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                            )
                        )
                    }
                    val distinctYRows = rowsByY.mapNotNull { row -> row.maxByOrNull { it.center.x } }.sortedBy { it.center.y }
                    distinctYRows.forEach { hole ->
                        candidateDims.add(
                            CadEntity.DimensionEntity(
                                dimensionType = DimensionType.ORDINATE_Y,
                                anchor1 = Point2D(overallBounds.maxX, hole.center.y),
                                anchor2 = Point2D(overallBounds.maxX + innerTrackOffset, hole.center.y),
                                dimensionLinePoint = Point2D(overallBounds.maxX + innerTrackOffset, hole.center.y),
                                sourceEntityIds = listOf(hole.id),
                                isAutoGenerated = true,
                                hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                            )
                        )
                    }
                } else {
                    val distinctXTargets = colsByX
                        .mapNotNull { col -> col.minByOrNull { it.center.y } }
                        .sortedBy { it.center.x }
                        .ifEmpty { bottomRow }

                    if (distinctXTargets.isNotEmpty()) {
                        val firstHole = distinctXTargets.first()
                        val leftEdgeOffset = firstHole.center.x - overallBounds.minX
                        if (leftEdgeOffset > 1e-2 && leftEdgeOffset < overallBounds.width - 1e-2) {
                            candidateDims.add(
                                CadEntity.DimensionEntity(
                                    dimensionType = DimensionType.LINEAR_HORIZONTAL,
                                    anchor1 = Point2D(overallBounds.minX, overallBounds.minY),
                                    anchor2 = firstHole.center,
                                    dimensionLinePoint = Point2D((overallBounds.minX + firstHole.center.x) * 0.5, bottomTrackY),
                                    sourceEntityIds = listOf(firstHole.id),
                                    isAutoGenerated = true,
                                    hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                                )
                            )
                        }

                        // Adjacent hole-to-hole horizontal pitches (avoids n*(n-1)/2 pairwise clutter)
                        for (i in 0 until distinctXTargets.size - 1) {
                            val c1 = distinctXTargets[i]
                            val c2 = distinctXTargets[i + 1]
                            val pitchX = abs(c2.center.x - c1.center.x)
                            if (pitchX > 1e-2) {
                                candidateDims.add(
                                    CadEntity.DimensionEntity(
                                        dimensionType = DimensionType.LINEAR_HORIZONTAL,
                                        anchor1 = c1.center,
                                        anchor2 = c2.center,
                                        dimensionLinePoint = Point2D((c1.center.x + c2.center.x) * 0.5, bottomTrackY),
                                        sourceEntityIds = listOf(c1.id, c2.id),
                                        isAutoGenerated = true,
                                        hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                                    )
                                )
                            }
                        }

                        // In Detailed mode, if right margin is asymmetric with left margin, explicitly dimension the right margin
                        val lastHole = distinctXTargets.last()
                        val rightEdgeOffset = overallBounds.maxX - lastHole.center.x
                        if (density == QDimDensityPolicy.DETAILED &&
                            rightEdgeOffset > 1e-2 &&
                            abs(rightEdgeOffset - leftEdgeOffset) > 1e-3
                        ) {
                            candidateDims.add(
                                CadEntity.DimensionEntity(
                                    dimensionType = DimensionType.LINEAR_HORIZONTAL,
                                    anchor1 = lastHole.center,
                                    anchor2 = Point2D(overallBounds.maxX, overallBounds.minY),
                                    dimensionLinePoint = Point2D((lastHole.center.x + overallBounds.maxX) * 0.5, bottomTrackY),
                                    sourceEntityIds = listOf(lastHole.id),
                                    isAutoGenerated = true,
                                    hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                                )
                            )
                        }
                    }

                    val distinctYTargets = rowsByY
                        .mapNotNull { row -> row.maxByOrNull { it.center.x } }
                        .sortedBy { it.center.y }
                        .ifEmpty { rightCol }

                    if (distinctYTargets.isNotEmpty()) {
                        val bottomHole = distinctYTargets.first()
                        val bottomEdgeOffset = bottomHole.center.y - overallBounds.minY
                        if (bottomEdgeOffset > 1e-2 && bottomEdgeOffset < overallBounds.height - 1e-2) {
                            candidateDims.add(
                                CadEntity.DimensionEntity(
                                    dimensionType = DimensionType.LINEAR_VERTICAL,
                                    anchor1 = Point2D(overallBounds.maxX, overallBounds.minY),
                                    anchor2 = bottomHole.center,
                                    dimensionLinePoint = Point2D(rightTrackX, (overallBounds.minY + bottomHole.center.y) * 0.5),
                                    sourceEntityIds = listOf(bottomHole.id),
                                    isAutoGenerated = true,
                                    hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                                )
                            )
                        }

                        for (i in 0 until distinctYTargets.size - 1) {
                            val c1 = distinctYTargets[i]
                            val c2 = distinctYTargets[i + 1]
                            val pitchY = abs(c2.center.y - c1.center.y)
                            if (pitchY > 1e-2) {
                                candidateDims.add(
                                    CadEntity.DimensionEntity(
                                        dimensionType = DimensionType.LINEAR_VERTICAL,
                                        anchor1 = c1.center,
                                        anchor2 = c2.center,
                                        dimensionLinePoint = Point2D(rightTrackX, (c1.center.y + c2.center.y) * 0.5),
                                        sourceEntityIds = listOf(c1.id, c2.id),
                                        isAutoGenerated = true,
                                        hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                                    )
                                )
                            }
                        }

                        val topHole = distinctYTargets.last()
                        val topEdgeOffset = overallBounds.maxY - topHole.center.y
                        if (density == QDimDensityPolicy.DETAILED &&
                            topEdgeOffset > 1e-2 &&
                            abs(topEdgeOffset - bottomEdgeOffset) > 1e-3
                        ) {
                            candidateDims.add(
                                CadEntity.DimensionEntity(
                                    dimensionType = DimensionType.LINEAR_VERTICAL,
                                    anchor1 = topHole.center,
                                    anchor2 = Point2D(overallBounds.maxX, overallBounds.maxY),
                                    dimensionLinePoint = Point2D(rightTrackX, (topHole.center.y + overallBounds.maxY) * 0.5),
                                    sourceEntityIds = listOf(topHole.id),
                                    isAutoGenerated = true,
                                    hierarchyTier = DimensionHierarchyTier.SECONDARY_FEATURE
                                )
                            )
                        }
                    }
                }
            }

            val radiusGroups = detectedArcs.groupBy { it.arc.layerName to (it.arc.radius * 10000.0).roundToLong() }
            for ((_, arcGroup) in radiusGroups) {
                // Choose the top-right-most arc in the group so the radial callout exits cleanly outside the part
                val repFeature = arcGroup.maxByOrNull { it.arc.midPoint.x + it.arc.midPoint.y } ?: arcGroup.first()
                val repArc = repFeature.arc
                val mid = repArc.midPoint
                val outwardAngle = repArc.center.angleToDeg(mid)
                val prefix = if (arcGroup.size > 1) "${arcGroup.size}× " else ""

                // Place a center mark for standalone arcs with radius >= 4.0
                if (repArc.radius >= 4.0) {
                    centerMarks.add(
                        CadEntity.CenterMarkEntity(
                            center = repArc.center,
                            radius = min(repArc.radius * 0.45, 5.0),
                            sourceEntityId = repFeature.sourceEntityId
                        )
                    )
                }

                val placement = findBestLeaderPlacement(
                    featureId = repFeature.sourceEntityId,
                    center = repArc.center,
                    radius = repArc.radius,
                    minClearanceRadius = repArc.radius,
                    preferredBaseAngle = outwardAngle,
                    allCircles = circles,
                    allArcs = detectedArcs.map { it.arc },
                    overallBounds = overallBounds,
                    placedLeaderBoxes = placedLeaderBoxes,
                    lockContactAngle = outwardAngle
                )

                placedLeaderBoxes.add(placement.reservedBox)

                candidateDims.add(
                    CadEntity.DimensionEntity(
                        dimensionType = DimensionType.RADIUS,
                        anchor1 = repArc.center,
                        anchor2 = mid,
                        dimensionLinePoint = placement.shoulderPoint,
                        customPrefix = prefix,
                        sourceEntityIds = arcGroup.map { it.sourceEntityId }.distinct(),
                        isAutoGenerated = true,
                        hierarchyTier = DimensionHierarchyTier.GEOMETRIC_CALLOUT
                    )
                )
            }

            // --- Polygon & Triangle Interior Vertex Angular Extraction (Sections 52, 53, 55.3 & 57) ---
            data class DetectedCornerAngle(
                val sourceEntityId: String,
                val vertex: Point2D,
                val arm1Pt: Point2D,
                val arm2Pt: Point2D,
                val bisectorAngleDeg: Double,
                val interiorAngleDeg: Double,
                val minIncidentEdgeLen: Double
            )

            val polyEntities = geometricTargets.filterIsInstance<CadEntity.PolylineEntity>().toMutableList()
            // Also synthesize a closed/open polyline topology from connected standalone LineEntity chains when no PolylineEntity covers them
            val standaloneLines = geometricTargets.filterIsInstance<CadEntity.LineEntity>()
            if (standaloneLines.size >= 2) {
                val chains = extractConnectedLineCornerPolylines(standaloneLines)
                polyEntities.addAll(chains)
            }

            for (poly in polyEntities) {
                val verts = poly.vertices
                if (verts.size < 3 && (!poly.isClosed || verts.size < 2)) continue
                val isTriangle = poly.isClosed && verts.size == 3
                val cornerCandidates = mutableListOf<DetectedCornerAngle>()
                val cornerIndices = if (poly.isClosed) verts.indices else (1 until verts.size - 1)
                val polyCentroid = Point2D(
                    verts.sumOf { it.position.x } / verts.size.coerceAtLeast(1),
                    verts.sumOf { it.position.y } / verts.size.coerceAtLeast(1)
                )

                for (i in cornerIndices) {
                    val prevIdx = (i - 1 + verts.size) % verts.size
                    val nextIdx = (i + 1) % verts.size
                    val prevV = verts[prevIdx]
                    val currV = verts[i]
                    val nextV = verts[nextIdx]
                    // Only measure true straight-edge intersections; bulged corners are fillets handled by radius callouts
                    if (abs(prevV.bulge) > 1e-4 || abs(currV.bulge) > 1e-4) continue

                    val len1 = currV.position.distanceTo(prevV.position)
                    val len2 = currV.position.distanceTo(nextV.position)
                    if (len1 <= 1.0 || len2 <= 1.0) continue

                    val ang1 = currV.position.angleToDeg(prevV.position)
                    val ang2 = currV.position.angleToDeg(nextV.position)
                    var sweep = ((ang2 - ang1) + 360.0) % 360.0
                    val startAng = if (sweep > 180.0) {
                        sweep = 360.0 - sweep
                        ang2
                    } else {
                        ang1
                    }
                    // Skip collinear / degenerate 180° or 0° vertices
                    if (sweep <= 1.0 || abs(sweep - 180.0) <= 1.0) continue
                    // Skip orthogonal 90° corners on 4+ vertex axis-aligned plates unless it is a triangle
                    val e1Orthogonal = abs(ang1 % 90.0) <= 0.5 || abs((ang1 % 90.0) - 90.0) <= 0.5
                    val e2Orthogonal = abs(ang2 % 90.0) <= 0.5 || abs((ang2 % 90.0) - 90.0) <= 0.5
                    if (!isTriangle && abs(sweep - 90.0) <= 0.5 && e1Orthogonal && e2Orthogonal) continue

                    val bisector = startAng + sweep * 0.5
                    val armDist = (min(len1, len2) * 0.32).coerceIn(4.0, 16.0)
                    val arm1Pt = currV.position.polarOffset(armDist, ang1)
                    val arm2Pt = currV.position.polarOffset(armDist, ang2)
                    // Ensure bisector points toward polygon interior (or toward centroid for triangles)
                    val testIn = currV.position.polarOffset(4.0, bisector)
                    val testOut = currV.position.polarOffset(4.0, bisector + 180.0)
                    val effectiveBisector = if (testIn.distanceTo(polyCentroid) <= testOut.distanceTo(polyCentroid)) {
                        bisector
                    } else {
                        (bisector + 180.0) % 360.0
                    }

                    cornerCandidates.add(
                        DetectedCornerAngle(
                            sourceEntityId = poly.id,
                            vertex = currV.position,
                            arm1Pt = arm1Pt,
                            arm2Pt = arm2Pt,
                            bisectorAngleDeg = effectiveBisector,
                            interiorAngleDeg = sweep,
                            minIncidentEdgeLen = min(len1, len2)
                        )
                    )
                }

                if (cornerCandidates.isNotEmpty()) {
                    // Check if manual angular dimension already covers this vertex
                    val unannotatedCorners = cornerCandidates.filter { cand ->
                        manualDimensions.none { m ->
                            m.dimensionType == DimensionType.ANGULAR &&
                                (m.angularVertex ?: m.anchor1).distanceTo(cand.vertex) <= 1.0
                        }
                    }

                    if (density == QDimDensityPolicy.BALANCED && poly.isClosed && unannotatedCorners.size >= 2) {
                        // In Balanced mode, group verified equal angles in the same closed polygon (e.g., 3× 60.0° for equilateral triangle)
                        val angleGroups = unannotatedCorners.groupBy { (it.interiorAngleDeg * 20.0).roundToLong() }
                        var groupIdx = 0
                        for ((_, grp) in angleGroups) {
                            val rep = grp.maxByOrNull { it.minIncidentEdgeLen } ?: grp.first()
                            val prefix = if (grp.size > 1) "${grp.size}× " else ""
                            val arcRadius = (rep.minIncidentEdgeLen * 0.28 + groupIdx * 2.5).coerceIn(6.0, 18.0)
                            val arcMidPt = rep.vertex.polarOffset(arcRadius, rep.bisectorAngleDeg)
                            candidateDims.add(
                                CadEntity.DimensionEntity(
                                    dimensionType = DimensionType.ANGULAR,
                                    anchor1 = rep.arm1Pt,
                                    anchor2 = rep.arm2Pt,
                                    dimensionLinePoint = arcMidPt,
                                    angularVertex = rep.vertex,
                                    customPrefix = prefix,
                                    sourceEntityIds = listOf(rep.sourceEntityId),
                                    isAutoGenerated = true,
                                    hierarchyTier = DimensionHierarchyTier.GEOMETRIC_CALLOUT
                                )
                            )
                            groupIdx++
                        }
                    } else {
                        // In Detailed mode (or open polyline), dimension every valid vertex angle on staggered radii
                        unannotatedCorners.forEachIndexed { cIdx, cand ->
                            val arcRadius = (cand.minIncidentEdgeLen * 0.26 + (cIdx % 3) * 2.4).coerceIn(5.5, 18.0)
                            val arcMidPt = cand.vertex.polarOffset(arcRadius, cand.bisectorAngleDeg)
                            candidateDims.add(
                                CadEntity.DimensionEntity(
                                    dimensionType = DimensionType.ANGULAR,
                                    anchor1 = cand.arm1Pt,
                                    anchor2 = cand.arm2Pt,
                                    dimensionLinePoint = arcMidPt,
                                    angularVertex = cand.vertex,
                                    sourceEntityIds = listOf(cand.sourceEntityId),
                                    isAutoGenerated = true,
                                    hierarchyTier = DimensionHierarchyTier.GEOMETRIC_CALLOUT
                                )
                            )
                        }
                    }
                }
            }
        }

        // --- TIER 3: Local Profile Feature Classification (Section 31) ---
        // Classifies every straight segment from standalone lines and polyline decomposition into:
        // - HORIZONTAL local features (e.g., stepped shoulders, recessed shelves, unequal top/bottom spans)
        // - VERTICAL local features (e.g., internal notch walls, stepped shoulders, asymmetric outer walls)
        // - INCLINED local features (chamfers, angled edges)
        val edgeDiagnostics = mutableListOf<EdgeDimensionDiagnostic>()
        val arcEndpoints = detectedArcs.flatMap { feat ->
            val a = feat.arc
            val pStart = a.center.polarOffset(a.radius, a.startAngleDeg)
            val pEnd = a.center.polarOffset(a.radius, a.startAngleDeg + a.sweepAngleDeg)
            listOf(pStart to a.radius, pEnd to a.radius)
        }

        fun findAdjacentFilletRadius(pt: Point2D): Double {
            return arcEndpoints.firstOrNull { (arcPt, _) -> arcPt.distanceTo(pt) <= 0.15 }?.second ?: 0.0
        }

        for ((srcId, line) in allLines) {
            val len = line.length
            val ang = ((line.angleDeg % 180.0) + 180.0) % 180.0
            val isHorizontal = abs(ang) < 1e-2 || abs(ang - 180.0) < 1e-2
            val isVertical = abs(ang - 90.0) < 1e-2
            val orientation = when {
                isHorizontal -> "HORIZONTAL"
                isVertical -> "VERTICAL"
                else -> "INCLINED"
            }

            if (len <= 1.0) {
                edgeDiagnostics.add(
                    EdgeDimensionDiagnostic(
                        sourceEntityId = srcId,
                        start = line.start,
                        end = line.end,
                        length = len,
                        orientation = orientation,
                        status = EdgeDimensionStatus.BELOW_MINIMUM_FEATURE_LENGTH,
                        reason = "Segment length (${"%.2f".format(len)}) is below minimum feature threshold (1.0)."
                    )
                )
                continue
            }

            if (isHorizontal) {
                val minX = min(line.start.x, line.end.x)
                val maxX = max(line.start.x, line.end.x)
                val segY = (line.start.y + line.end.y) * 0.5
                val rStart = findAdjacentFilletRadius(line.start)
                val rEnd = findAdjacentFilletRadius(line.end)
                val isFullWidth = abs(len - overallBounds.width) <= 0.05
                val isFilletTrimmedOuterWidth = (abs(segY - overallBounds.minY) <= 0.05 || abs(segY - overallBounds.maxY) <= 0.05) &&
                    (rStart > 0.0 || rEnd > 0.0) &&
                    abs((len + rStart + rEnd) - overallBounds.width) <= 0.15

                val coveredByManual = hasEquivalentManualLinear(manualDimensions, DimensionType.LINEAR_HORIZONTAL, len)
                val alreadyInCandidates = candidateDims.any {
                    it.dimensionType == DimensionType.LINEAR_HORIZONTAL &&
                        abs(min(it.anchor1.x, it.anchor2.x) - minX) <= 0.05 &&
                        abs(max(it.anchor1.x, it.anchor2.x) - maxX) <= 0.05 &&
                        abs(((it.anchor1.y + it.anchor2.y) * 0.5) - segY) <= 0.5
                }

                when {
                    coveredByManual -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.COVERED_BY_MANUAL_DIMENSION,
                                reason = "Horizontal span ${"%.2f".format(len)} already covered by manual dimension."
                            )
                        )
                    }
                    isFullWidth -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.COVERED_BY_PRIMARY_OVERALL,
                                reason = "Horizontal span equals primary overall width ${"%.2f".format(overallBounds.width)}."
                            )
                        )
                    }
                    isFilletTrimmedOuterWidth && density != QDimDensityPolicy.DETAILED -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.DERIVABLE_FROM_OVERALL_AND_FILLETS,
                                reason = "Outer tangent straight segment derivable from overall width and corner fillets."
                            )
                        )
                    }
                    density == QDimDensityPolicy.SPARSE -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.SUPPRESSED_BY_SPARSE_POLICY,
                                reason = "Local horizontal feature suppressed under Sparse density policy."
                            )
                        )
                    }
                    len <= 2.0 -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.BELOW_MINIMUM_FEATURE_LENGTH,
                                reason = "Horizontal segment (${"%.2f".format(len)}) below 2.0 minimum local feature threshold."
                            )
                        )
                    }
                    !alreadyInCandidates -> {
                        val trackY = if (segY >= overallBounds.maxY - 1.0) {
                            overallBounds.maxY + innerTrackOffset
                        } else {
                            overallBounds.minY - innerTrackOffset
                        }
                        val localDim = CadEntity.DimensionEntity(
                            dimensionType = DimensionType.LINEAR_HORIZONTAL,
                            anchor1 = Point2D(minX, segY),
                            anchor2 = Point2D(maxX, segY),
                            dimensionLinePoint = Point2D((minX + maxX) * 0.5, trackY),
                            sourceEntityIds = listOf(srcId),
                            isAutoGenerated = true,
                            hierarchyTier = DimensionHierarchyTier.TERTIARY_LOCAL
                        )
                        candidateDims.add(localDim)
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.EMITTED_EXPLICIT,
                                emittedDimensionId = localDim.id,
                                reason = "Local horizontal feature (${"%.2f".format(len)}) explicitly dimensioned."
                            )
                        )
                    }
                }
            } else if (isVertical) {
                val minY = min(line.start.y, line.end.y)
                val maxY = max(line.start.y, line.end.y)
                val segX = (line.start.x + line.end.x) * 0.5
                val rStart = findAdjacentFilletRadius(line.start)
                val rEnd = findAdjacentFilletRadius(line.end)
                val isFullHeight = abs(len - overallBounds.height) <= 0.05
                val isFilletTrimmedOuterHeight = (abs(segX - overallBounds.minX) <= 0.05 || abs(segX - overallBounds.maxX) <= 0.05) &&
                    (rStart > 0.0 || rEnd > 0.0) &&
                    abs((len + rStart + rEnd) - overallBounds.height) <= 0.15

                val coveredByManual = hasEquivalentManualLinear(manualDimensions, DimensionType.LINEAR_VERTICAL, len)
                val alreadyInCandidates = candidateDims.any {
                    it.dimensionType == DimensionType.LINEAR_VERTICAL &&
                        abs(min(it.anchor1.y, it.anchor2.y) - minY) <= 0.05 &&
                        abs(max(it.anchor1.y, it.anchor2.y) - maxY) <= 0.05 &&
                        abs(((it.anchor1.x + it.anchor2.x) * 0.5) - segX) <= 0.5
                }

                when {
                    coveredByManual -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.COVERED_BY_MANUAL_DIMENSION,
                                reason = "Vertical span ${"%.2f".format(len)} already covered by manual dimension."
                            )
                        )
                    }
                    isFullHeight -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.COVERED_BY_PRIMARY_OVERALL,
                                reason = "Vertical span equals primary overall height ${"%.2f".format(overallBounds.height)}."
                            )
                        )
                    }
                    isFilletTrimmedOuterHeight && density != QDimDensityPolicy.DETAILED -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.DERIVABLE_FROM_OVERALL_AND_FILLETS,
                                reason = "Outer tangent straight segment derivable from overall height and corner fillets."
                            )
                        )
                    }
                    density == QDimDensityPolicy.SPARSE -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.SUPPRESSED_BY_SPARSE_POLICY,
                                reason = "Local vertical feature suppressed under Sparse density policy."
                            )
                        )
                    }
                    len <= 2.0 -> {
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.BELOW_MINIMUM_FEATURE_LENGTH,
                                reason = "Vertical segment (${"%.2f".format(len)}) below 2.0 minimum local feature threshold."
                            )
                        )
                    }
                    !alreadyInCandidates -> {
                        val trackX = if (segX <= overallBounds.center.x) {
                            overallBounds.minX - innerTrackOffset
                        } else {
                            overallBounds.maxX + innerTrackOffset
                        }
                        val localDim = CadEntity.DimensionEntity(
                            dimensionType = DimensionType.LINEAR_VERTICAL,
                            anchor1 = Point2D(segX, minY),
                            anchor2 = Point2D(segX, maxY),
                            dimensionLinePoint = Point2D(trackX, (minY + maxY) * 0.5),
                            sourceEntityIds = listOf(srcId),
                            isAutoGenerated = true,
                            hierarchyTier = DimensionHierarchyTier.TERTIARY_LOCAL
                        )
                        candidateDims.add(localDim)
                        edgeDiagnostics.add(
                            EdgeDimensionDiagnostic(
                                sourceEntityId = srcId,
                                start = line.start,
                                end = line.end,
                                length = len,
                                orientation = orientation,
                                status = EdgeDimensionStatus.EMITTED_EXPLICIT,
                                emittedDimensionId = localDim.id,
                                reason = "Local vertical feature (${"%.2f".format(len)}) explicitly dimensioned."
                            )
                        )
                    }
                }
            } else {
                // Inclined / chamfered edge: always offset outward away from overallBounds.center
                if (density == QDimDensityPolicy.SPARSE) {
                    edgeDiagnostics.add(
                        EdgeDimensionDiagnostic(
                            sourceEntityId = srcId,
                            start = line.start,
                            end = line.end,
                            length = len,
                            orientation = orientation,
                            status = EdgeDimensionStatus.SUPPRESSED_BY_SPARSE_POLICY,
                            reason = "Inclined edge suppressed under Sparse density policy."
                        )
                    )
                } else if (len <= 3.0) {
                    edgeDiagnostics.add(
                        EdgeDimensionDiagnostic(
                            sourceEntityId = srcId,
                            start = line.start,
                            end = line.end,
                            length = len,
                            orientation = orientation,
                            status = EdgeDimensionStatus.BELOW_MINIMUM_FEATURE_LENGTH,
                            reason = "Inclined segment (${"%.2f".format(len)}) below 3.0 minimum local feature threshold."
                        )
                    )
                } else {
                    val mid = line.midpoint
                    val n1Rad = Math.toRadians(line.angleDeg + 90.0)
                    val n2Rad = Math.toRadians(line.angleDeg - 90.0)
                    val cand1 = Point2D(mid.x + 10.0 * cos(n1Rad), mid.y + 10.0 * sin(n1Rad))
                    val cand2 = Point2D(mid.x + 10.0 * cos(n2Rad), mid.y + 10.0 * sin(n2Rad))
                    val outwardPt = if (cand1.distanceTo(overallBounds.center) >= cand2.distanceTo(overallBounds.center)) {
                        cand1
                    } else {
                        cand2
                    }
                    val alignedDim = CadEntity.DimensionEntity(
                        dimensionType = DimensionType.ALIGNED,
                        anchor1 = line.start,
                        anchor2 = line.end,
                        dimensionLinePoint = outwardPt,
                        sourceEntityIds = listOf(srcId),
                        isAutoGenerated = true,
                        hierarchyTier = DimensionHierarchyTier.TERTIARY_LOCAL
                    )
                    candidateDims.add(alignedDim)
                    edgeDiagnostics.add(
                        EdgeDimensionDiagnostic(
                            sourceEntityId = srcId,
                            start = line.start,
                            end = line.end,
                            length = len,
                            orientation = orientation,
                            status = EdgeDimensionStatus.EMITTED_EXPLICIT,
                            emittedDimensionId = alignedDim.id,
                            reason = "Inclined edge (${"%.2f".format(len)}) dimensioned as ALIGNED on exterior track."
                        )
                    )
                }
            }
        }

        val alignmentReport = DimensionAlignmentEngine.alignAndArrangeDimensions(
            candidateDimensions = candidateDims,
            overallBounds = overallBounds,
            existingManualDimensions = manualDimensions,
            obstacleCircles = circles,
            obstacleArcs = detectedArcs.map { it.arc },
            obstacleLines = allLines.map { it.second },
            completenessFindings = completenessFindings,
            edgeDiagnostics = edgeDiagnostics,
            arrangementPreference = arrangementPreference,
            densityPolicy = density,
            style = style,
            precision = precision,
            storageUnit = storageUnit,
            displayUnit = displayUnit,
            viewport = viewport
        )

        return (preservedEntities + centerMarks + alignmentReport.resolvedDimensions) to alignmentReport
    }

    private data class LeaderPlacementResult(
        val rimContactPoint: Point2D,
        val shoulderPoint: Point2D,
        val reservedBox: BoundingBox2D
    )

    /**
     * Evaluates candidate radial leader angles and shoulder extensions to find an unobstructed
     * ISO/ASME leader placement whose ray and horizontal landing shelf never cut through holes or edges.
     */
    private fun findBestLeaderPlacement(
        featureId: String,
        center: Point2D,
        radius: Double,
        minClearanceRadius: Double,
        preferredBaseAngle: Double,
        allCircles: List<CadEntity.CircleEntity>,
        allArcs: List<CadEntity.ArcEntity>,
        overallBounds: BoundingBox2D,
        placedLeaderBoxes: List<BoundingBox2D>,
        lockContactAngle: Double?
    ): LeaderPlacementResult {
        val candidateAngles = if (lockContactAngle != null) {
            listOf(lockContactAngle)
        } else {
            // Avoid near-horizontal (0, 180) and near-vertical (90, -90) angles per ISO 129-1 / ASME Y14.5
            listOf(
                22.0, -22.0, 38.0, -38.0, 52.0, -52.0, 66.0, -66.0,
                114.0, -114.0, 128.0, -128.0, 142.0, -142.0, 158.0, -158.0
            ).sortedBy { ang ->
                val diff = abs(((ang - preferredBaseAngle + 540.0) % 360.0) - 180.0)
                diff
            }
        }

        val baseOut = max(radius + max(10.0, radius * 0.45), minClearanceRadius + 9.5)
        val candidateDistances = listOf(
            baseOut,
            baseOut + 6.0,
            baseOut + 12.0,
            baseOut + 20.0,
            baseOut + 30.0
        )

        val shelfWidth = 19.0
        val shelfHeight = 7.5

        var bestResult: LeaderPlacementResult? = null
        var bestScore = Double.MAX_VALUE

        for (ang in candidateAngles) {
            val rimPt = center.polarOffset(radius, ang)
            val shelfDir = if (cos(Math.toRadians(ang)) >= -0.05) 1.0 else -1.0

            for (dist in candidateDistances) {
                val shoulderPt = center.polarOffset(dist, ang)
                val landingEndPt = shoulderPt.offset(shelfDir * shelfWidth, 0.0)

                val minShelfX = min(shoulderPt.x, landingEndPt.x) - 1.5
                val maxShelfX = max(shoulderPt.x, landingEndPt.x) + 1.5
                val shelfBox = BoundingBox2D(
                    minX = minShelfX,
                    minY = shoulderPt.y - 1.5,
                    maxX = maxShelfX,
                    maxY = shoulderPt.y + shelfHeight
                )

                var penalty = (dist - baseOut) * 1.2

                // 1. Check collision with all circles (except the feature itself)
                for (c in allCircles) {
                    if (c.id == featureId) continue
                    val clearance = c.radius + 3.2
                    val dRay = CadGeometryKernel.distancePointToSegment(c.center, rimPt, shoulderPt)
                    val dShelf = CadGeometryKernel.distancePointToSegment(c.center, shoulderPt, landingEndPt)
                    if (dRay < clearance || dShelf < clearance) {
                        penalty += 12000.0 + (clearance - min(dRay, dShelf)) * 500.0
                    }
                    val cBox = BoundingBox2D(
                        c.center.x - c.radius - 2.5,
                        c.center.y - c.radius - 2.5,
                        c.center.x + c.radius + 2.5,
                        c.center.y + c.radius + 2.5
                    )
                    if (shelfBox.intersects(cBox, tolerance = 0.5)) {
                        penalty += 9000.0
                    }
                }

                // 2. Check collision with standalone/fillet arcs (except same center)
                for (a in allArcs) {
                    if (a.center.distanceTo(center) < 0.5) continue
                    val dShelf = a.midPoint.distanceTo(shoulderPt)
                    if (dShelf < a.radius + 3.0) {
                        penalty += 3000.0
                    }
                }

                // 3. Avoid placing the horizontal shelf directly on top of outer boundary edges
                if (abs(shoulderPt.y - overallBounds.maxY) < 4.2 || abs(shoulderPt.y - overallBounds.minY) < 4.2) {
                    penalty += 2500.0
                }
                if (abs(shoulderPt.x - overallBounds.minX) < 3.5 || abs(shoulderPt.x - overallBounds.maxX) < 3.5) {
                    penalty += 1500.0
                }

                // 4. Check collision with already placed dimension/leader boxes
                for (box in placedLeaderBoxes) {
                    if (shelfBox.intersects(box, tolerance = 1.5)) {
                        penalty += 8000.0
                    }
                }

                if (penalty < bestScore) {
                    bestScore = penalty
                    bestResult = LeaderPlacementResult(
                        rimContactPoint = rimPt,
                        shoulderPoint = shoulderPt,
                        reservedBox = shelfBox
                    )
                }
            }
        }

        return bestResult ?: run {
            val fallbackAngle = lockContactAngle ?: 38.0
            val rim = center.polarOffset(radius, fallbackAngle)
            val sh = center.polarOffset(baseOut, fallbackAngle)
            LeaderPlacementResult(
                rimContactPoint = rim,
                shoulderPoint = sh,
                reservedBox = BoundingBox2D(sh.x - 10.0, sh.y - 2.0, sh.x + 10.0, sh.y + 7.0)
            )
        }
    }

    private fun hasEquivalentManualLinear(
        manualDims: List<CadEntity.DimensionEntity>,
        type: DimensionType,
        measuredVal: Double
    ): Boolean = manualDims.any {
        it.dimensionType == type && abs(it.measuredModelValue() - measuredVal) < 0.05
    }

    private fun clusterCirclesByCoord(
        circles: List<CadEntity.CircleEntity>,
        tolerance: Double,
        coordSelector: (CadEntity.CircleEntity) -> Double
    ): List<List<CadEntity.CircleEntity>> {
        if (circles.isEmpty()) return emptyList()
        val sorted = circles.sortedBy(coordSelector)
        val clusters = mutableListOf<MutableList<CadEntity.CircleEntity>>()
        for (c in sorted) {
            val v = coordSelector(c)
            val existing = clusters.lastOrNull()
            if (existing != null && abs(v - coordSelector(existing.first())) <= tolerance) {
                existing.add(c)
            } else {
                clusters.add(mutableListOf(c))
            }
        }
        return clusters
    }

    private fun extractConnectedLineCornerPolylines(
        lines: List<CadEntity.LineEntity>,
        endpointTol: Double = 0.05
    ): List<CadEntity.PolylineEntity> {
        if (lines.size < 2) return emptyList()
        val remaining = lines.toMutableList()
        val result = mutableListOf<CadEntity.PolylineEntity>()

        while (remaining.isNotEmpty()) {
            val first = remaining.removeAt(0)
            val pts = mutableListOf(first.start, first.end)
            var grew = true
            while (grew && remaining.isNotEmpty()) {
                grew = false
                val head = pts.first()
                val tail = pts.last()
                val matchIdx = remaining.indexOfFirst { seg ->
                    seg.start.distanceTo(tail) <= endpointTol ||
                        seg.end.distanceTo(tail) <= endpointTol ||
                        seg.start.distanceTo(head) <= endpointTol ||
                        seg.end.distanceTo(head) <= endpointTol
                }
                if (matchIdx >= 0) {
                    val seg = remaining.removeAt(matchIdx)
                    when {
                        seg.start.distanceTo(tail) <= endpointTol -> pts.add(seg.end)
                        seg.end.distanceTo(tail) <= endpointTol -> pts.add(seg.start)
                        seg.end.distanceTo(head) <= endpointTol -> pts.add(0, seg.start)
                        seg.start.distanceTo(head) <= endpointTol -> pts.add(0, seg.end)
                    }
                    grew = true
                }
            }
            if (pts.size >= 3) {
                val isClosedLoop = pts.first().distanceTo(pts.last()) <= endpointTol
                val cleanPts = if (isClosedLoop) pts.dropLast(1) else pts
                if (cleanPts.size >= 3) {
                    result.add(
                        CadEntity.PolylineEntity(
                            id = "${first.id}_chain",
                            layerName = first.layerName,
                            vertices = cleanPts.map { PolylineVertex(it, 0.0) },
                            isClosed = isClosedLoop
                        )
                    )
                }
            }
        }
        return result
    }
}

/**
 * 10.2 DimensionLayoutEngine
 * Responsibilities:
 * - Group related dimensions into clean chains and baselines.
 * - Calculate extension-line positions and track offsets so overall dimensions sit outside subordinate dimensions.
 * - Detect and resolve collisions between dimension lines, text boxes, and geometry while preserving radial ray alignment.
 */
object DimensionLayoutEngine {

    fun optimizeDimensionLayout(
        candidateDimensions: List<CadEntity.DimensionEntity>,
        overallBounds: BoundingBox2D,
        existingManualDimensions: List<CadEntity.DimensionEntity>,
        obstacleCircles: List<CadEntity.CircleEntity> = emptyList()
    ): List<CadEntity.DimensionEntity> {
        if (candidateDimensions.isEmpty()) return emptyList()

        val spanScale = max(overallBounds.width, overallBounds.height).coerceAtLeast(20.0)
        val innerTrackOffset = (spanScale * 0.09).coerceIn(8.0, 22.0)
        val outerTrackSpacing = (spanScale * 0.08).coerceIn(7.0, 18.0)

        val laidOut = mutableListOf<CadEntity.DimensionEntity>()
        val occupiedLabelBoxes = existingManualDimensions.map { estimateLabelBox(it, spanScale) }.toMutableList()

        // 1. Place Secondary Horizontal Chain at Bottom Track 1, Overall Horizontal at Top Track 1
        val horizSecondary = candidateDimensions.filter {
            it.dimensionType == DimensionType.LINEAR_HORIZONTAL &&
                it.hierarchyTier != DimensionHierarchyTier.PRIMARY_OVERALL
        }.sortedBy { min(it.anchor1.x, it.anchor2.x) }

        val bottomChainY = overallBounds.minY - innerTrackOffset
        horizSecondary.forEach { dim ->
            val midX = (dim.anchor1.x + dim.anchor2.x) * 0.5
            laidOut.add(dim.copy(dimensionLinePoint = Point2D(midX, bottomChainY)))
        }

        val horizPrimary = candidateDimensions.filter {
            it.dimensionType == DimensionType.LINEAR_HORIZONTAL &&
                it.hierarchyTier == DimensionHierarchyTier.PRIMARY_OVERALL
        }
        val topPrimaryY = overallBounds.maxY + innerTrackOffset
        horizPrimary.forEachIndexed { idx, dim ->
            val midX = (dim.anchor1.x + dim.anchor2.x) * 0.5
            val trackY = topPrimaryY + idx * outerTrackSpacing
            laidOut.add(dim.copy(dimensionLinePoint = Point2D(midX, trackY)))
        }

        // 2. Place Secondary Vertical Chain at Right Track 1, Primary Overall Vertical at Left Track 1
        val vertSecondary = candidateDimensions.filter {
            it.dimensionType == DimensionType.LINEAR_VERTICAL &&
                it.hierarchyTier != DimensionHierarchyTier.PRIMARY_OVERALL
        }.sortedBy { min(it.anchor1.y, it.anchor2.y) }

        val rightChainX = overallBounds.maxX + innerTrackOffset
        vertSecondary.forEach { dim ->
            val midY = (dim.anchor1.y + dim.anchor2.y) * 0.5
            laidOut.add(dim.copy(dimensionLinePoint = Point2D(rightChainX, midY)))
        }

        val vertPrimary = candidateDimensions.filter {
            it.dimensionType == DimensionType.LINEAR_VERTICAL &&
                it.hierarchyTier == DimensionHierarchyTier.PRIMARY_OVERALL
        }
        val leftPrimaryX = overallBounds.minX - innerTrackOffset
        vertPrimary.forEachIndexed { idx, dim ->
            val midY = (dim.anchor1.y + dim.anchor2.y) * 0.5
            val trackX = leftPrimaryX - idx * outerTrackSpacing
            laidOut.add(dim.copy(dimensionLinePoint = Point2D(trackX, midY)))
        }

        // 3. Place Radial, Diametric, Aligned, Angular & Ordinate dimensions with ray-preserving collision avoidance
        val otherDims = candidateDimensions.filter {
            it.dimensionType != DimensionType.LINEAR_HORIZONTAL &&
                it.dimensionType != DimensionType.LINEAR_VERTICAL
        }

        laidOut.forEach { occupiedLabelBoxes.add(estimateLabelBox(it, spanScale)) }

        for (dim in otherDims) {
            var adjusted = dim
            var candidateBox = estimateLabelBox(adjusted, spanScale)
            var attempt = 0
            while (attempt < 6 && (
                    occupiedLabelBoxes.any { it.intersects(candidateBox, tolerance = 1.2) } ||
                        collidesWithAnyCircle(adjusted, obstacleCircles)
                    )
            ) {
                attempt++
                if (adjusted.dimensionType == DimensionType.DIAMETER) {
                    val radius = adjusted.anchor1.distanceTo(adjusted.anchor2)
                    val baseAngle = adjusted.anchor1.angleToDeg(adjusted.anchor2)
                    val delta = if (attempt % 2 == 1) 18.0 * ((attempt + 1) / 2) else -18.0 * (attempt / 2)
                    val newAngle = baseAngle + delta
                    val newDist = adjusted.anchor1.distanceTo(adjusted.dimensionLinePoint) + (attempt * 3.5)
                    adjusted = adjusted.copy(
                        anchor2 = adjusted.anchor1.polarOffset(radius, newAngle),
                        dimensionLinePoint = adjusted.anchor1.polarOffset(newDist, newAngle)
                    )
                } else if (adjusted.dimensionType == DimensionType.RADIUS) {
                    val rayAngle = adjusted.anchor1.angleToDeg(adjusted.anchor2)
                    val newDist = adjusted.anchor1.distanceTo(adjusted.dimensionLinePoint) + (attempt * 4.5)
                    adjusted = adjusted.copy(
                        dimensionLinePoint = adjusted.anchor1.polarOffset(newDist, rayAngle)
                    )
                } else {
                    val shiftAngle = 35.0 * attempt
                    val dist = adjusted.anchor1.distanceTo(adjusted.dimensionLinePoint) + (attempt * 3.5)
                    adjusted = adjusted.copy(
                        dimensionLinePoint = adjusted.anchor1.polarOffset(dist, shiftAngle)
                    )
                }
                candidateBox = estimateLabelBox(adjusted, spanScale)
            }
            occupiedLabelBoxes.add(candidateBox)
            laidOut.add(adjusted)
        }

        return laidOut
    }

    private fun collidesWithAnyCircle(
        dim: CadEntity.DimensionEntity,
        circles: List<CadEntity.CircleEntity>
    ): Boolean {
        if (dim.dimensionType != DimensionType.DIAMETER && dim.dimensionType != DimensionType.RADIUS) return false
        val rim = dim.anchor2
        val sh = dim.dimensionLinePoint
        val rayAngle = dim.anchor1.angleToDeg(rim)
        val shelfDir = if (cos(Math.toRadians(rayAngle)) >= -0.05) 1.0 else -1.0
        val end = sh.offset(shelfDir * 18.0, 0.0)
        return circles.any { c ->
            c.id !in dim.sourceEntityIds &&
                (CadGeometryKernel.distancePointToSegment(c.center, rim, sh) < c.radius + 2.5 ||
                    CadGeometryKernel.distancePointToSegment(c.center, sh, end) < c.radius + 2.5)
        }
    }

    private fun estimateLabelBox(dim: CadEntity.DimensionEntity, spanScale: Double): BoundingBox2D {
        val w = (spanScale * 0.14).coerceIn(9.0, 30.0)
        val h = (spanScale * 0.06).coerceIn(4.5, 11.0)
        val p = dim.dimensionLinePoint
        return BoundingBox2D(p.x - w * 0.5, p.y - h * 0.5, p.x + w * 0.5, p.y + h * 0.5)
    }
}

/**
 * 10.3 AdaptiveAnnotationRenderer
 * Distinguishes stored model-space dimension geometry from screen-space viewport presentation:
 * - Measured values never change when zooming.
 * - Produces ISO 129-1 / ASME Y14.5 compliant Radial (R), Diametric (⌀), Angular (∠), and Linear callouts.
 * - Includes center marks, collinear radial leader rays, single circumference arrowheads, and horizontal landing shelves.
 */
data class AdaptiveDimensionRenderPlan(
    val isVisibleAtCurrentZoom: Boolean,
    val labelText: String,
    val ext1StartModel: Point2D,
    val ext1EndModel: Point2D,
    val ext2StartModel: Point2D,
    val ext2EndModel: Point2D,
    val dimLineStartModel: Point2D,
    val dimLineEndModel: Point2D,
    val arrowsInside: Boolean,
    val textInside: Boolean,
    val textPositionModel: Point2D,
    val textRotationDeg: Float,
    val arrowLengthModel: Double,
    val arrowWidthModel: Double,
    val fontSizeSp: Float,
    // ISO / ASME Radial, Diametric, and Angular Engineering Callout Geometry
    val isRadialOrDiametric: Boolean = false,
    val isDiameterCallout: Boolean = false,
    val circleOrArcCenterModel: Point2D? = null,
    val rimContactPointModel: Point2D? = null,
    val oppositeRimPointModel: Point2D? = null,
    val leaderShoulderModel: Point2D? = null,
    val leaderLandingEndModel: Point2D? = null,
    val isAngularArc: Boolean = false,
    val angularCenterModel: Point2D? = null,
    val angularRadiusModel: Double = 0.0,
    val angularStartDeg: Double = 0.0,
    val angularSweepDeg: Double = 0.0
)

object AdaptiveAnnotationRenderer {

    fun computeRenderPlan(
        dim: CadEntity.DimensionEntity,
        precision: PrecisionFormatConfig,
        storageUnit: CadUnit,
        displayUnit: CadUnit,
        style: DimensionStyleConfig,
        viewport: ViewportTransform
    ): AdaptiveDimensionRenderPlan {
        val label = dim.formattedLabel(precision, storageUnit, displayUnit)
        val pxPerUnit = viewport.pixelsPerModelUnit.coerceAtLeast(0.05f)

        val fontSizeSp = (style.baseTextHeightMm.toFloat() * pxPerUnit * 0.85f).coerceIn(9.5f, 13.5f)
        val effectiveArrowPx = (style.baseArrowLengthMm.toFloat() * pxPerUnit).coerceIn(6.5f, 14f)
        val arrowLenModel = (effectiveArrowPx / pxPerUnit).toDouble()
        val arrowWidModel = arrowLenModel * 0.36
        val estTextWidthPx = label.length * fontSizeSp * 0.62f
        val estTextWidthModel = (estTextWidthPx / pxPerUnit).toDouble()

        val gapModel = (style.extensionLineGapMm).coerceIn(0.4, 2.5)
        val overshootModel = (style.extensionLineOvershootMm).coerceIn(0.8, 3.0)

        when (dim.dimensionType) {
            DimensionType.LINEAR_HORIZONTAL -> {
                val x1 = min(dim.anchor1.x, dim.anchor2.x)
                val x2 = max(dim.anchor1.x, dim.anchor2.x)
                val yAnchor1 = if (dim.anchor1.x <= dim.anchor2.x) dim.anchor1.y else dim.anchor2.y
                val yAnchor2 = if (dim.anchor1.x <= dim.anchor2.x) dim.anchor2.y else dim.anchor1.y
                val dimY = dim.dimensionLinePoint.y
                val spanModel = abs(x2 - x1)
                val spanPx = spanModel * pxPerUnit

                val isVisible = spanPx >= 12.0 || dim.hierarchyTier == DimensionHierarchyTier.PRIMARY_OVERALL
                val arrowsInside = spanModel >= arrowLenModel * 2.6
                val textInside = spanModel >= (estTextWidthModel + arrowLenModel * 2.4)

                val dir1 = if (dimY >= yAnchor1) 1.0 else -1.0
                val dir2 = if (dimY >= yAnchor2) 1.0 else -1.0

                val p1 = Point2D(x1, dimY)
                val p2 = Point2D(x2, dimY)
                val textPos = if (textInside) {
                    Point2D((x1 + x2) * 0.5, dimY + (arrowWidModel * 1.4))
                } else {
                    Point2D(x2 + arrowLenModel * 1.6 + estTextWidthModel * 0.5, dimY)
                }

                return AdaptiveDimensionRenderPlan(
                    isVisibleAtCurrentZoom = isVisible,
                    labelText = label,
                    ext1StartModel = Point2D(x1, yAnchor1 + dir1 * gapModel),
                    ext1EndModel = Point2D(x1, dimY + dir1 * overshootModel),
                    ext2StartModel = Point2D(x2, yAnchor2 + dir2 * gapModel),
                    ext2EndModel = Point2D(x2, dimY + dir2 * overshootModel),
                    dimLineStartModel = p1,
                    dimLineEndModel = p2,
                    arrowsInside = arrowsInside,
                    textInside = textInside,
                    textPositionModel = textPos,
                    textRotationDeg = 0f,
                    arrowLengthModel = arrowLenModel,
                    arrowWidthModel = arrowWidModel,
                    fontSizeSp = fontSizeSp
                )
            }

            DimensionType.LINEAR_VERTICAL -> {
                val y1 = min(dim.anchor1.y, dim.anchor2.y)
                val y2 = max(dim.anchor1.y, dim.anchor2.y)
                val xAnchor1 = if (dim.anchor1.y <= dim.anchor2.y) dim.anchor1.x else dim.anchor2.x
                val xAnchor2 = if (dim.anchor1.y <= dim.anchor2.y) dim.anchor2.x else dim.anchor1.x
                val dimX = dim.dimensionLinePoint.x
                val spanModel = abs(y2 - y1)
                val spanPx = spanModel * pxPerUnit
                val isVisible = spanPx >= 12.0 || dim.hierarchyTier == DimensionHierarchyTier.PRIMARY_OVERALL

                val arrowsInside = spanModel >= arrowLenModel * 2.6
                val textInside = spanModel >= (estTextWidthModel + arrowLenModel * 2.4)

                val dir1 = if (dimX >= xAnchor1) 1.0 else -1.0
                val dir2 = if (dimX >= xAnchor2) 1.0 else -1.0

                val p1 = Point2D(dimX, y1)
                val p2 = Point2D(dimX, y2)
                val textPos = if (textInside) {
                    Point2D(dimX - arrowWidModel * 1.5, (y1 + y2) * 0.5)
                } else {
                    Point2D(dimX, y2 + arrowLenModel * 1.5 + (fontSizeSp / pxPerUnit))
                }

                return AdaptiveDimensionRenderPlan(
                    isVisibleAtCurrentZoom = isVisible,
                    labelText = label,
                    ext1StartModel = Point2D(xAnchor1 + dir1 * gapModel, y1),
                    ext1EndModel = Point2D(dimX + dir1 * overshootModel, y1),
                    ext2StartModel = Point2D(xAnchor2 + dir2 * gapModel, y2),
                    ext2EndModel = Point2D(dimX + dir2 * overshootModel, y2),
                    dimLineStartModel = p1,
                    dimLineEndModel = p2,
                    arrowsInside = arrowsInside,
                    textInside = textInside,
                    textPositionModel = textPos,
                    textRotationDeg = -90f,
                    arrowLengthModel = arrowLenModel,
                    arrowWidthModel = arrowWidModel,
                    fontSizeSp = fontSizeSp
                )
            }

            DimensionType.RADIUS, DimensionType.DIAMETER -> {
                // ISO 129-1 / ASME Y14.5 Engineering Radial & Diametric Leader Callout:
                // - Center is dim.anchor1; exact rim contact point on arc/circle is dim.anchor2.
                // - Radial leader line is strictly collinear with (center -> rimContactPoint) so the arrow
                //   points directly at the true center of curvature.
                // - Ends in a horizontal landing shelf (shoulder -> landingEnd) with the R/⌀ label above the shelf.
                val center = dim.anchor1
                val radiusModel = center.distanceTo(dim.anchor2).coerceAtLeast(0.5)
                val rayAngleDeg = if (center.distanceTo(dim.anchor2) > 1e-4) {
                    center.angleToDeg(dim.anchor2)
                } else {
                    center.angleToDeg(dim.dimensionLinePoint)
                }

                val rimContact = center.polarOffset(radiusModel, rayAngleDeg)
                val oppositeRim = center.polarOffset(radiusModel, rayAngleDeg + 180.0)

                val minShoulderRadius = radiusModel + max(arrowLenModel * 2.4, radiusModel * 0.35)
                val userShoulderRadius = center.distanceTo(dim.dimensionLinePoint)
                val effectiveShoulderDist = max(minShoulderRadius, userShoulderRadius)
                val shoulderPt = center.polarOffset(effectiveShoulderDist, rayAngleDeg)

                val shelfDirection = if (cos(Math.toRadians(rayAngleDeg)) >= -0.05) 1.0 else -1.0
                val shelfLenModel = max(estTextWidthModel * 1.08, arrowLenModel * 2.5)
                val landingEndPt = shoulderPt.offset(shelfDirection * shelfLenModel, 0.0)

                // Position text centered above the horizontal shelf
                val shelfMidX = (shoulderPt.x + landingEndPt.x) * 0.5
                val textYOffset = arrowWidModel * 1.45
                val textPos = Point2D(shelfMidX, shoulderPt.y + textYOffset)

                val isDiameter = dim.dimensionType == DimensionType.DIAMETER
                val diameterSpanModel = radiusModel * 2.0
                val arrowsInside = if (isDiameter) {
                    diameterSpanModel >= (estTextWidthModel + arrowLenModel * 3.2)
                } else {
                    radiusModel >= (estTextWidthModel + arrowLenModel * 2.8)
                }

                return AdaptiveDimensionRenderPlan(
                    isVisibleAtCurrentZoom = true,
                    labelText = label,
                    ext1StartModel = center,
                    ext1EndModel = rimContact,
                    ext2StartModel = oppositeRim,
                    ext2EndModel = rimContact,
                    dimLineStartModel = rimContact,
                    dimLineEndModel = shoulderPt,
                    arrowsInside = arrowsInside,
                    textInside = false,
                    textPositionModel = textPos,
                    textRotationDeg = 0f,
                    arrowLengthModel = arrowLenModel,
                    arrowWidthModel = arrowWidModel,
                    fontSizeSp = fontSizeSp,
                    isRadialOrDiametric = true,
                    isDiameterCallout = isDiameter,
                    circleOrArcCenterModel = center,
                    rimContactPointModel = rimContact,
                    oppositeRimPointModel = if (isDiameter) oppositeRim else null,
                    leaderShoulderModel = shoulderPt,
                    leaderLandingEndModel = landingEndPt
                )
            }

            DimensionType.ANGULAR -> {
                val vertex = dim.angularVertex ?: dim.anchor1
                val arm1Angle = vertex.angleToDeg(dim.anchor1)
                val arm2Angle = vertex.angleToDeg(dim.anchor2)
                var sweep = ((arm2Angle - arm1Angle) + 360.0) % 360.0
                val startAng = if (sweep > 180.0) {
                    sweep = 360.0 - sweep
                    arm2Angle
                } else {
                    arm1Angle
                }
                val arcRadius = max(
                    vertex.distanceTo(dim.dimensionLinePoint),
                    max(vertex.distanceTo(dim.anchor1), vertex.distanceTo(dim.anchor2)) * 0.65
                ).coerceAtLeast(arrowLenModel * 3.0)

                val arcStartPt = vertex.polarOffset(arcRadius, startAng)
                val arcEndPt = vertex.polarOffset(arcRadius, startAng + sweep)
                val midAngle = startAng + sweep * 0.5
                val textPos = vertex.polarOffset(arcRadius + arrowWidModel * 1.8, midAngle)

                val ext1S = vertex.polarOffset(gapModel, startAng)
                val ext1E = vertex.polarOffset(arcRadius + overshootModel, startAng)
                val ext2S = vertex.polarOffset(gapModel, startAng + sweep)
                val ext2E = vertex.polarOffset(arcRadius + overshootModel, startAng + sweep)

                val arcLenModel = Math.toRadians(sweep) * arcRadius
                val arrowsInside = arcLenModel >= arrowLenModel * 2.4

                return AdaptiveDimensionRenderPlan(
                    isVisibleAtCurrentZoom = true,
                    labelText = label,
                    ext1StartModel = ext1S,
                    ext1EndModel = ext1E,
                    ext2StartModel = ext2S,
                    ext2EndModel = ext2E,
                    dimLineStartModel = arcStartPt,
                    dimLineEndModel = arcEndPt,
                    arrowsInside = arrowsInside,
                    textInside = true,
                    textPositionModel = textPos,
                    textRotationDeg = 0f,
                    arrowLengthModel = arrowLenModel,
                    arrowWidthModel = arrowWidModel,
                    fontSizeSp = fontSizeSp,
                    isAngularArc = true,
                    angularCenterModel = vertex,
                    angularRadiusModel = arcRadius,
                    angularStartDeg = startAng,
                    angularSweepDeg = sweep
                )
            }

            else -> {
                // Aligned & Ordinate
                val spanModel = dim.anchor1.distanceTo(dim.anchor2)
                val arrowsInside = spanModel >= arrowLenModel * 2.5
                val textInside = spanModel >= (estTextWidthModel + arrowLenModel * 2.2)
                val mid = dim.anchor1.midpointTo(dim.anchor2)
                val offsetVec = Point2D(dim.dimensionLinePoint.x - mid.x, dim.dimensionLinePoint.y - mid.y)
                val d1 = dim.anchor1.offset(offsetVec.x, offsetVec.y)
                val d2 = dim.anchor2.offset(offsetVec.x, offsetVec.y)
                val lineAngle = d1.angleToDeg(d2)
                val normAngleRad = Math.toRadians(lineAngle + 90.0)
                val textMid = d1.midpointTo(d2)
                val textPos = Point2D(
                    textMid.x + cos(normAngleRad) * (arrowWidModel * 1.4),
                    textMid.y + sin(normAngleRad) * (arrowWidModel * 1.4)
                )
                return AdaptiveDimensionRenderPlan(
                    isVisibleAtCurrentZoom = true,
                    labelText = label,
                    ext1StartModel = dim.anchor1,
                    ext1EndModel = d1,
                    ext2StartModel = dim.anchor2,
                    ext2EndModel = d2,
                    dimLineStartModel = d1,
                    dimLineEndModel = d2,
                    arrowsInside = arrowsInside,
                    textInside = textInside,
                    textPositionModel = textPos,
                    textRotationDeg = 0f,
                    arrowLengthModel = arrowLenModel,
                    arrowWidthModel = arrowWidModel,
                    fontSizeSp = fontSizeSp
                )
            }
        }
    }
}
